#include "Vat.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CVat::Init(void)
{
	msLevel.miDepth = 0;
	msLevel.miMark = 0;
	miCount = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Depth(SLevel* psLevel)
{
	return psLevel->miDepth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CVat::Fill(SLevel* psLevel, int iAmount)
{
	psLevel->miDepth += iAmount;
	(*psLevel).miMark = Depth(psLevel);
	msLevel = *psLevel;
	return psLevel->miDepth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CDeepVat::Fill(SLevel* psLevel, int iAmount)
{
	psLevel->miDepth += iAmount * 2;
	return CVat::Fill(psLevel, 0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CVat::Drain(const SLevel& sLevel)
{
	const SLevel*	psSame;

	psSame = &sLevel;
	miCount = sLevel.miDepth + Depth(&msLevel);
	msLevel = sLevel;
	return psSame->miMark;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CVat::Check(SLevel* psLevel)
{
	if (psLevel == 0)
	{
		return 0;
	}
	return psLevel->miDepth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CVat::Step(SLevel* psLevel)
{
	psLevel++;
	psLevel->miMark = 1;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CVat::Sum(SLevel* psLevel, int iTimes)
{
	if (iTimes == 0)
	{
		return psLevel->miDepth;
	}
	return psLevel->miMark + Sum(psLevel, iTimes - 1);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Use(CVat* pcVat, CDeepVat* pcDeep)
{
	SLevel	sLevel;
	SLevel*	psMine;
	SLevel&	sOther = pcVat->msLevel;
	SLevel*	psLate;
	int		iTotal;

	psMine = &sLevel;
	psLate = &sLevel;
	SLevel*	psLocal = &pcVat->msLevel;
	iTotal = pcVat->Fill(&sLevel, 1);
	iTotal += pcDeep->Fill(psMine, 2);
	iTotal += pcVat->Drain(sLevel);
	iTotal += pcVat->Drain(*psMine);
	iTotal += pcVat->Check(0);
	iTotal += psLocal->miDepth + (*psLocal).miMark + Depth(psLocal);
	sOther.miDepth = iTotal;
	iTotal += Depth(&sOther) + sOther.miMark;
	return iTotal + pcVat->Sum(psLate, 2);
}
