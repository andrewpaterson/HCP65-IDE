#include "Probe.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CProbe::CProbe(SLevel& sLevel) : msLevel(sLevel), miCount(0)
{
	mpsSpare = &sLevel;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CProbe::Read(void)
{
	return msLevel.miDepth + Mark(&msLevel) + mpsSpare->miMark;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CProbe::Set(int iDepth)
{
	msLevel.miDepth = iDepth;
	this->msLevel.miMark = iDepth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Probe(CProbe* pcProbe, SLevel* psLevel)
{
	CProbe	cOther(*psLevel);
	SLevel	sCopy;

	sCopy = pcProbe->msLevel;
	pcProbe->msLevel.miMark = cOther.msLevel.miDepth + sCopy.miMark;
	return Mark(&pcProbe->msLevel) + (&cOther.msLevel)->miMark;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Mark(SLevel* psLevel)
{
	return psLevel->miMark;
}
