#include "Calc.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCalc::Init(void)
{
	muiCount = 0;
	miScale = 1;
	mszName = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CCalc::GetCount(void)
{
	return muiCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CCalc::Scaled(int iValue)
{
	return iValue * miScale;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
char* CCalc::GetName(void)
{
	return mszName;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
unsigned long long CCalc::BigValue(void)
{
	return muiCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CCalc::Total(int iExtra)
{
	int		iResult;
	CCalc*	pcOther;

	pcOther = this;
	iResult = Scaled(iExtra) + miScale * 2;
	if (GetCount() > 4)
	{
		iResult += miScale * 2;
		iResult += pcOther->GetCount();
	}
	GetName();
	Init();
	return iResult + GetCount();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CCalc::Reset(void)
{
	muiCount = GetCount() + 1;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CCalc::Big(void)
{
	int		iResult;
	char*	sz;

	sz = GetName();
	iResult = (int)BigValue() + (sz ? 1 : 0);
	return iResult;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Next(int* piStep)
{
	(*piStep)++;
	return *piStep;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Drift(int iBase, int iStep)
{
	int		iTotal;

	iTotal = iBase * 2;
	iBase += iStep;
	iTotal += iBase * 2;
	return iTotal + Next(&iStep) + Next(&iStep);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Area(CCalc* pcCalc, int iWidth)
{
	return (pcCalc->miScale + 7) * iWidth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Wide(int iWidth)
{
	return iWidth * iWidth + iWidth;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Areas(CCalc* pcCalc, int i)
{
	return Area(pcCalc, 3) + Area(pcCalc + 1, i) + Wide(Next(&i));
}
