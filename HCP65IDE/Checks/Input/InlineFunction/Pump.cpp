#include "Pump.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPump::Init(int iRate)
{
	miRate = iRate;
	miCount = 0;
	miLimit = 10;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CPump::Step(int iBy)
{
	int	iNext;

	iNext = miCount + iBy;
	miCount = iNext;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CPump::Run(int iTimes)
{
	int	i;

	for (i = 0; i < iTimes; i++)
	{
		Step(i + 1);
	}
	return miCount + Scaled(i + 1);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CPump::Kind(void)
{
	return 1;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CPump::Loop(int iDepth)
{
	if (iDepth > 0)
	{
		return Loop(iDepth - 1);
	}
	return 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CPump::Pick(int iA)
{
	if (iA > miLimit)
	{
		return miLimit;
	}
	return iA;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CPump::Bump(int iA)
{
	iA = iA + 1;
	return iA;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Twice(int iValue)
{
	return iValue * 2;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void Report(CPump* pcPump, int iWhat)
{
	pcPump->Kind();
	pcPump->miLimit = iWhat;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int UsePump(CPump* pcPump)
{
	CPump		cOther;
	CSlot<long>	cSlot;
	int			iTotal;

	cOther.Init(3);
	cOther.Step(2);
	iTotal = Twice(pcPump->GetRate() + 1) * 2;
	iTotal += pcPump->Scaled(iTotal - 1);
	Report(&cOther, iTotal);
	cSlot.miUsed = 2;
	iTotal = cSlot.Bytes();
	return Twice(iTotal);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int UseBump(CPump* pcPump, int iA)
{
	int	iTotal;

	iTotal = pcPump->Bump(3);
	iTotal = iTotal + pcPump->Bump(iA) * 2;
	if (pcPump->Bump(iTotal) > pcPump->Bump(4))
	{
		iTotal = 0;
	}
	while (pcPump->Bump(1) < iTotal)
	{
		iTotal--;
	}
	return (iTotal > 0) ? pcPump->Bump(iTotal) : 0;
}
