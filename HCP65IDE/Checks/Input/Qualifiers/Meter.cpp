#include "Meter.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMeter::Init(void)
{
	miLevel = 0;
	maiMarks[3] = 0;
	msMark.iAt = 0;
	mpcNext = this;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Level(void)
{
	return miLevel;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CFineMeter::Level(void)
{
	return miLevel * 2;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Raise(int iBy)
{
	miLevel += iBy;
	maiMarks[0] = miLevel;
	return miLevel;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Mark(void)
{
	msMark.iAt = 1;
	return msMark.iAt;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Both(void)
{
	return Level() + Raise(1);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Next(void)
{
	mpcNext->miLevel = 2;
	return mpcNext->Level() + miLevel;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Scale(int iValue)
{
	return iValue * 3;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMeter::Twice(int iValue)
{
	return Scale(iValue) + miLevel;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CMeter* CMeter::Find(void)
{
	miLevel++;
	return this;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Use(CMeter* pcMeter)
{
	CMeter	cMeter;
	int		iTotal;

	cMeter.Init();
	iTotal = cMeter.Scale(2);
	iTotal += pcMeter->Scale(3);
	iTotal += pcMeter->Find()->Scale(4);
	iTotal += cMeter.Zero() + cMeter.Top();
	return iTotal + cMeter.Both() + cMeter.Next() + cMeter.Mark() + cMeter.Twice(1);
}
