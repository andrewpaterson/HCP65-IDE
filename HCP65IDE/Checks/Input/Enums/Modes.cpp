#include "Modes.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMotor::Init(void)
{
	meMode = EM_Off;
	meState = ES_Idle;
	meLevel = EL_Low;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMotor::Speed(void)
{
	switch (meMode)
	{
	case EM_Slow:
		return 1;
	case EMode::EM_Fast:
		return 2;
	default:
		return (meState == ES_Running) ? 3 : 0;
	}
}
