#include "Mix.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMix::Init(int iBase)
{
	miBase = iBase;
	miCount = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMix::Blend(int iA, int iB) const
{
	int	iSum;
	int	iResult;

	iSum = iA + iB;
	iSum = iSum * miBase;
	iResult = iSum * 2;
	return iResult;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMix::Sum(int iLimit)
{
	int	i;
	int	iTotal;

	iTotal = 0;
	for (i = 0; i < iLimit; i++)
	{
		iTotal += i * miBase;
	}
	return iTotal;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMix::Both(int iA)
{
	int	iLow;
	int	iHigh;

	iLow = iA - 1;
	iHigh = iA + 1;
	miCount = iLow * iHigh;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMix::Early(int iA)
{
	int	iHalf;

	iHalf = iA / 2;
	if (iHalf > miBase)
	{
		return miBase;
	}
	return iHalf;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CMix::Move(SPoint* psPoint)
{
	SPoint	sOther;

	sOther.iX = psPoint->iX + miBase;
	sOther.iY = psPoint->iY;
	psPoint->iX = sOther.iY;
	psPoint->iY = sOther.iX;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int UseMix(CMix* pcMix)
{
	CPile<int>	cPile;
	int			iFirst;
	int			iSecond;

	iFirst = pcMix->Blend(1, 2);
	iSecond = pcMix->Sum(iFirst);
	while (iSecond > 100)
	{
		iSecond = iSecond / 2;
		if (iSecond == 77)
		{
			break;
		}
	}
	cPile.miDepth = Larger(iFirst, iSecond);
	return cPile.Weigh(2);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int First(int iA, int iB)
{
	int	iSum;

	iSum = iA + iB;
	iSum = iSum * 3;
	return iSum;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Second(int iX, int iY)
{
	int	iAll;
	int	iMore;

	iAll = iX + iY;
	iAll = iAll * 3;
	iMore = iAll + 1;
	return iMore;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Third(int iX, int iY)
{
	int	iAll;

	iAll = iX - iY;
	iAll = iAll * 3;
	return iAll;
}
