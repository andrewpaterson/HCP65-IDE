#include "Pipe.h"
#include "Gauge.h"
#include "Drum.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CDrum::Init(CGauge* pcGauge)
{
	mpcGauge = pcGauge;
	mcPipe.Init();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CDrum::Bore(void)
{
	return mcPipe.miBore + mpcGauge->Read();
}
