#include "Shapes.h"


namespace Geometry
{
	int	giCount = 1;


	//////////////////////////////////////////////////////////////////////////
	//
	//
	//////////////////////////////////////////////////////////////////////////
	void CPoint::Init(TLength iX, TLength iY)
	{
		miX = iX;
		miY = Detail::Twice(iY);
	}


	//////////////////////////////////////////////////////////////////////////
	//
	//
	//////////////////////////////////////////////////////////////////////////
	TLength CPoint::Sum(void)
	{
		return miX + miY;
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
Geometry::TLength Geometry::Area(CPoint* pcPoint)
{
	return pcPoint->Sum() * giCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Geometry::Detail::Twice(int i)
{
	return i * 2;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void Drawing::Plot(Geometry::CPoint* pcPoint)
{
	pcPoint->Init(1, 2);
}
