#ifndef __GAUGE_H__
#define __GAUGE_H__


int		ReadGauge(int iGauge, int iScale = 1);
int		ResetGauge(int iGauge);


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
inline int ClampGauge(int iValue, int iMax = 100)
{
	return (iValue > iMax) ? iMax : iValue;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
template<class M>
M MaxGauge(M a, M b)
{
	return (a > b) ? a : b;
}


#endif // __GAUGE_H__
