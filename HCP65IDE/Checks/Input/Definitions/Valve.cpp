#include "Valve.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CValve::Init(void)
{
	miFlow = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
long CValve::Open(int iFlow, int iTime)
{
	return iFlow * iTime;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CValve::Close(void)
{
	miFlow = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CValve::Turn(int iDegrees)
{
	return iDegrees + miFlow;
}
