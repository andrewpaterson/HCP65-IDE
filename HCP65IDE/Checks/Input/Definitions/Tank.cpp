#include "Tank.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CTank::CTank(int iCapacity) : miLevel(0), miSize(iCapacity)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTank::Init(int iSize)
{
	miLevel = 0;
	miSize = iSize;
}


//////////////////////////////////////////////////////////////////////////
//
// Whether it holds all it can.
//
//////////////////////////////////////////////////////////////////////////
bool CTank::IsFull(void) const
{
	return miLevel >= miSize;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTank::Empty(void)
{
	if (miLevel > 0)
	{
		miLevel = 0;
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CountTanks(CTank* pacTanks, int iCount)
{
	return iCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTank::Reset(int iLevel)
{
	miLevel = iLevel;
}
