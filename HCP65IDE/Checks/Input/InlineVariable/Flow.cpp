int FlowSum(int iA, int iB)
{
	int	iSum;
	int	iResult;

	iSum = iA + iB;
	iResult = iSum * 2 + Scale(iSum);
	return iResult;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int FlowCall(int iA)
{
	int	iScaled = Scale(iA);
	int	iOnce = Scale(iA + 1);

	return iScaled + iScaled + iOnce;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int FlowChanged(int iA)
{
	int	iCount;
	int	iFirst;
	int	iSecond;

	iCount = iA;
	iCount++;
	iFirst = iA * 2;
	iA = 7;
	iSecond = iFirst;
	return iCount + iSecond;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int FlowRefused(int iA)
{
	int		iX, iY;
	int		iTaken;
	int		iTwice;
	int		iLate;
	int		iNever;
	int*	piWhere;

	iX = iA;
	iY = iX;
	iTaken = iA;
	piWhere = &iTaken;
	iTwice = 1;
	iTwice = 2;
	if (iA)
	{
		iLate = 3;
	}
	return iY + *piWhere + iTwice + iLate + iNever;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Scale(int iValue)
{
	return iValue * 3;
}
