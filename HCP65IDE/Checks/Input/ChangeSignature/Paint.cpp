#include "Paint.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBrush::Init(int iSize, const char* szName)
{
	miSize = iSize + (szName ? 1 : 0);
}


//////////////////////////////////////////////////////////////////////////
//
// Its parameters have other names here than in the class.
//
//////////////////////////////////////////////////////////////////////////
int CBrush::Mix(int iR, int iG, int iB)
{
	int	iTotal;

	iTotal = iR + iG * 2;
	return iTotal + iB + iR;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBrush::Draw(int iX, int iY)
{
	miSize = iX;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CBrush::Clear(void)
{
	miSize = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CSpray::Draw(int iX, int iY)
{
	miSize = iX + iY;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Blend(int iFirst, int iSecond)
{
	return iFirst + iSecond;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Blend(int iFirst, int iSecond, int iThird)
{
	return iFirst + iSecond + iThird;
}


