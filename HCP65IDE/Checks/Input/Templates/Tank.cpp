#include "Tank.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CTank::CTank(void)
{
	mpcGauge = 0;
	miCount = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CTank::~CTank(void)
{
	miCount = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CTank::Init(CGauge* pcGauge)
{
	mpcGauge = pcGauge;
	mcSpare.miLevel = 2;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CTank::Level(void)
{
	CGauge*	pcGauge;

	pcGauge = mpcGauge;
	return pcGauge->Read() + mcSpare.Read() + miCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int UseTank(void)
{
	CTank	cTank;
	CGauge	cGauge;

	cGauge.miLevel = 1;
	cTank.Init(&cGauge);
	return cTank.Level() + cTank.Same()->miCount;
}
