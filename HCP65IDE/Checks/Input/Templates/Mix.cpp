#include "Mix.h"


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Total(CGauge* pcGauge, int iCount)
{
	CGauge*	pcOther;

	pcOther = pcGauge;
	return pcOther->Read() * iCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Make(int iSeed)
{
	CGauge	cGauge;

	cGauge.miLevel = iSeed;
	return cGauge.Read();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Marked(CGauge* pcGauge)
{
	CGauge::SMark	sMark;

	sMark.iAt = pcGauge->Read();
	return sMark.iAt;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMixer::Sum(CGauge* pcGauge, int iTimes)
{
	return pcGauge->Read() * iTimes + miTotal;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CMixer::Blend(CGauge* pcGauge)
{
	return pcGauge->Read();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
static int Local(CGauge* pcGauge)
{
	return pcGauge->Read();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Twice(int iValue)
{
	int		iResult;

	iResult = iValue * 2;
	return iResult;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int Use(void)
{
	CGauge	cGauge;
	CMixer	cMixer;

	cGauge.miLevel = 1;
	cMixer.miTotal = 0;
	return Total(&cGauge, 2) + Make(3) + Marked(&cGauge) + cMixer.Sum(&cGauge, 2) + cMixer.Blend(&cGauge) + Local(&cGauge) + Twice(4);
}
