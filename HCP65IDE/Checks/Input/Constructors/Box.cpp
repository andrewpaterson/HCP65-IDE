CBox::CBox(int iWidth, int iHeight)
{
	miWidth = iWidth;
	miHeight = iHeight;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CCrate::CCrate(int iSize) : CBox(iSize, iSize), mcInner(1, 2)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int UseBoxes(void)
{
	CBox	cBox(3, 4);
	CBox	cOther{5, 6};
	CBox*	pcBox;
	CBox	cThird = CBox(7, 8);

	pcBox = new CBox(9, 10);
	return cBox.miWidth + cOther.miWidth + pcBox->miHeight + cThird.miWidth + CBox(11, 12).miHeight;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CLid::CLid(void)
{
	miSize = 0;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int UseLids(void)
{
	CLid	cLid;
	CLid*	pcLid;
	CLid	cOther = CLid();

	pcLid = new CLid;
	return cLid.miSize + pcLid->miSize + cOther.miSize;
}
