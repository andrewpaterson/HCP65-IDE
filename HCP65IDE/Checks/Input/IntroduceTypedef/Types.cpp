unsigned long long CItems::Total(CList<SItem>* pcOther)
{
	unsigned long long	ulResult;
	CList<SItem>*		pcItems;

	pcItems = pcOther;
	ulResult = (unsigned long long)pcItems->miCount;
	return ulResult + mulTotal + pcItems->Last()->iValue;
}
