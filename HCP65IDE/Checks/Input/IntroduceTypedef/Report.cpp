int CountItems(CList<SItem>* pcList)
{
	return pcList->miCount;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
int CountBoth(CList<SItem>* pcFirst, REPORT_LIST* pcSecond)
{
	CList<SItem>*	pcList;

	pcList = pcSecond;
	return CountItems(pcFirst) + CountItems(pcList);
}
